export function getService(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug);
}

/** Куда ведёт пакет: на свою страницу услуги, посадочная — в раздел корпоративных сайтов. */
export function packageHref(slug: PackageSlug): string {
  if (slug === "landing") return "/services/corporate-websites#landing";
  if (slug === "support") return "/pricing#support";
  const service = services.find((s) => s.packageSlug === slug);
  return service ? `/services/${service.slug}` : "/pricing";
}

export function serviceForPackage(slug: PackageSlug): Service | undefined {
  return services.find((s) => s.packageSlug === slug);
}
