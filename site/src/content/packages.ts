// Порядок показа везде одинаковый: основной ряд по чеку от сайта к аудиту, затем дополнительно.
const order: PackageSlug[] = [
  "corporate",
  "catalog",
  "landing",
  "ux-audit",
  "design",
  "ai",
  "support",
];

export const packages: readonly ServicePackage[] = [...allPackages].sort(
  (a, b) => order.indexOf(a.slug) - order.indexOf(b.slug),
);
export const mainPackages = packages.filter((p) => p.group === "main");
export const extraPackages = packages.filter((p) => p.group === "extra");

/** Подпись действия у пакета — одна для всех: «Обсудить: Сайт-каталог». */
export function ctaText(pack: ServicePackage): string {
  return `Обсудить: ${pack.title}`;
}

const rub = new Intl.NumberFormat("ru-RU", {
  style: "currency",
  currency: "RUB",
  maximumFractionDigits: 0,
});

export function formatPrice(value: number): string {
  return rub.format(value);
}

/** Стартовая цена пакета так, как она читается везде на сайте: «от 180 000 ₽», «анализ 20 000 ₽». */
export function priceText(pack: ServicePackage): string {
  return `${pack.pricePrefix ?? "от"} ${formatPrice(pack.priceFrom)}`;
}

export function getPackage(slug: PackageSlug): ServicePackage {
  const found = packages.find((p) => p.slug === slug);
  if (!found) throw new Error(`Unknown package: ${slug}`);
  return found;
}

